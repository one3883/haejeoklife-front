function childhoodEntry(town, slot) {
  const [street, ...props] = childhoodTowns[town];
  const prop = props[slot];
  const guest = childhoodGuests[town]?.[slot - 4];
  const [title, situation, ...options] = childhoodLocalStories[town + '/' + slot] || childhoodStories[slot];
  const intro = guest ? guest + (slot === 4 ? " 곁에 모인 구경꾼들이 " : " 쪽으로 사진기를 맞추고 ") : "";
  return {
    title: street + ": " + prop + " 소동 — " + title,
    body: situation.replace("{guest}", intro).replace("{o}", "‘" + prop + "’"),
    guest, age: childhoodAges[slot],
    choices: options.map((line, index) => {
      const [action, immediate, payoff] = line.split("|");
      return { action, immediate, payoff, due: 21 + (slot + index) % 6 };
    }),
  };
}

function childhoodEligible(town, slot) {
  const guest = childhoodGuests[town]?.[slot - 4];
  if (!guest) return true;
  const years = childhoodWindows[town + '/' + guest];
  const year = p.birthYear + realAge(childhoodAges[slot]);
  return !!years && year >= years[0] && year <= years[1];
}

function childhoodState() {
  return p.flags.childhoodSeeds ||= { town: null, slots: [], choices: {} };
}

function childhoodSeedScenes() {
  const town = p.place.name;
  if (!childhoodTowns[town]) return [];
  const state = childhoodState();
  if (state.town !== town) {
    const remaining = childhoodAges.map((_, i) => i).filter(i =>
      childhoodAges[i] >= p.age && childhoodEligible(town, i));
    for (let i = remaining.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [remaining[i], remaining[j]] = [remaining[j], remaining[i]];
    }
    state.target ||= 4 + Math.floor(Math.random() * 2);
    state.slots = remaining.slice(0, Math.max(0, state.target - Object.keys(state.choices).length));
    state.town = town;
  }
  const slot = state.slots.find(i => childhoodAges[i] === p.age);
  const key = town + "/" + slot;
  if (slot === undefined || state.choices[key]) return [];
  const entry = childhoodEntry(town, slot);
  const choices = entry.choices.map(({action, immediate, due}, index) => ({
    title: action, desc: ["관계 +2 · 행복 -1", "장사 +2 · 관계 -1", "행복 +2 · 동네 평판 -1"][index],
    run() {
      if (state.choices[key]) return;
      state.choices[key] = { town, slot, index, due, paid: false };
      if (index === 0) { p.relationship += 2; p.happiness--; }
      if (index === 1) { sk("장사", 2); p.relationship--; }
      if (index === 2) { p.happiness += 2; lrep(-1); }
      log(immediate);
    },
  }));
  return [K("seed_" + key, entry.title, entry.body, choices)];
}

function childhoodPayoffs() {
  const records = Object.values(p.flags.childhoodSeeds?.choices || {});
  return records.filter(r => !r.paid && r.due === p.age).map(r => {
    const entry = childhoodEntry(r.town, r.slot);
    const prop = childhoodTowns[r.town][r.slot + 1];
    const memory = entry.choices[r.index];
    return {
      key: "childhood_return_" + r.town + "/" + r.slot,
      title: prop + "의 뒷이야기", essential: true,
      body: r.town + "에서 벌였던 " + prop + " 소동 기억나세요? " + memory.payoff,
      effect() {
        if (r.paid) return;
        r.paid = true;
        p.money += [12000, 20000, 15000][r.index];
        p.reputation += [4, 1, 3][r.index];
      },
      summary: prop + " 소동의 뜻밖의 답례를 받음",
    };
  });
}
